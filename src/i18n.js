export const supportedLanguages = ["he", "en"];
export function translate(language, key, params = {}) {
  const message = messages[language]?.[key] ?? messages.he[key];
  if (message === undefined) throw new Error(`Unknown translation: ${key}`);
  return message.replace(/\{(\w+)\}/g, (_, name) =>
    String(params[name] ?? `{${name}}`),
  );
}
export function applyTranslations(root, language) {
  root.documentElement.lang = language;
  root.documentElement.dir = language === "he" ? "rtl" : "ltr";
  root.title = translate(language, "pageTitle");
  for (const element of root.querySelectorAll("[data-i18n]"))
    element.textContent = translate(language, element.dataset.i18n);
  for (const attr of ["placeholder", "aria-label", "alt"])
    for (const element of root.querySelectorAll(`[data-i18n-${attr}]`))
      element.setAttribute(
        attr,
        translate(language, element.getAttribute(`data-i18n-${attr}`)),
      );
}
